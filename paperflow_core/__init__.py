"""PaperFlow 核心包。

一个把「读论文」变成「可积累的能力」的最小流水线。只有三条命令：

* ``init``     配置 Obsidian 库、第 1 周起始日、长期目标位置
* ``week``     每周一次：全局回顾 + 检索筛选 + 推 Zotero + 写清单和周报
* ``summary``  周 / 月总结

组织方式：**发散地读，收敛地攒**。

* 每周推荐是发散的（同一条检索式打出去，让 AI 挑）。
* 积累是收敛的：每份周报末尾带一个 ``<!-- PF:WEEK {...} -->`` 机器可读块，
  下一次运行时只读这些块 + 你新写的笔记，所以看的是全局进度而不是上一周。

三条硬边界：

1. 脚本**不碰 git**，也不替你写代码——工程部分只做推荐。
2. AI 只在你给的真实候选里选，不许凭空编论文；编出来的会被丢弃并报警告。
3. 任何一步失败（没 key、断网、Zotero 没配）都必须照样产出文件。

包名是 ``paperflow_core`` 而不是 ``paperflow``：仓库根目录有同名入口脚本
``paperflow.py``，同名包会导致导入歧义。
"""

